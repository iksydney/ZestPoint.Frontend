// Reads .env.<mode> and writes src/environments/environment.ts, the static file the app reads at runtime.
// Usage: node scripts/generate-env.mjs [development|production]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.argv[2] ?? process.env.APP_ENV ?? 'development';

const vars = {};
for (const line of readFileSync(resolve(root, `.env.${mode}`), 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
  if (m) vars[m[1]] = m[2];
}

const apiBaseUrl = (vars.API_BASE_URL ?? '').replace(/\/+$/, '');
const out = `// GENERATED by scripts/generate-env.mjs from .env.${mode} - edit the .env file, not this one.
export const environment = {
  production: ${mode === 'production'},
  /** Absolute API root without trailing slash. Empty = same-origin relative /api (dev proxy). */
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
  siteUrl: ${JSON.stringify(vars.SITE_URL ?? '')}
};
`;
const target = resolve(root, 'src/environments/environment.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`environment.ts generated for "${mode}" (API: ${apiBaseUrl || 'relative /api'})`);
